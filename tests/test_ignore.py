import re
from pathlib import Path

import pytest

from prettycsharp.ignore import Ignorer, clear_caches, glob_regex, is_generated


@pytest.fixture(autouse=True)
def fresh_caches() -> None:
    clear_caches()


def touch(path: Path, text: str = "class A { }\n") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


@pytest.mark.parametrize(
    ("pattern", "path", "matches"),
    [
        ("*.cs", "A.cs", True),
        ("*.cs", "src/A.cs", False),
        ("src/**/*.cs", "src/a/b/A.cs", True),
        ("src/**/*.cs", "src/A.cs", True),
        ("**/Old", "x/y/Old", True),
        ("A?.cs", "AB.cs", True),
        ("[ab].cs", "b.cs", True),
        ("[!ab].cs", "b.cs", False),
    ],
)
def test_glob_regex(pattern: str, path: str, matches: bool) -> None:
    assert (re.fullmatch(glob_regex(pattern), path) is not None) is matches


def test_gitignore_applies_inside_a_repository(tmp_path: Path) -> None:
    (tmp_path / ".git").mkdir()
    touch(tmp_path / ".gitignore", "Generated/\n*.tmp.cs\n!Keep.tmp.cs\n# comment\n")
    ignorer = Ignorer()
    assert ignorer.skip_file(touch(tmp_path / "Generated" / "A.cs"))
    assert ignorer.skip_file(touch(tmp_path / "src" / "B.tmp.cs"))
    assert not ignorer.skip_file(touch(tmp_path / "src" / "Keep.tmp.cs"))
    assert not ignorer.skip_file(touch(tmp_path / "src" / "C.cs"))
    assert not Ignorer(respect_gitignore=False).skip_file(tmp_path / "Generated" / "A.cs")


def test_gitignore_outside_a_repository_is_ignored(tmp_path: Path) -> None:
    touch(tmp_path / ".gitignore", "*.cs\n")
    assert not Ignorer().skip_file(touch(tmp_path / "A.cs"))


def test_anchored_patterns_and_nested_ignore_files(tmp_path: Path) -> None:
    touch(tmp_path / ".prettycsharpignore", "/Top.cs\n")
    touch(tmp_path / "sub" / ".prettycsharpignore", "Local.cs\n")
    ignorer = Ignorer()
    assert ignorer.skip_file(touch(tmp_path / "Top.cs"))
    assert not ignorer.skip_file(touch(tmp_path / "sub" / "Top.cs"))
    assert ignorer.skip_file(touch(tmp_path / "sub" / "deeper" / "Local.cs"))
    assert not ignorer.skip_file(touch(tmp_path / "Local.cs"))


def test_generated_files(tmp_path: Path) -> None:
    ignorer = Ignorer()
    assert ignorer.skip_file(touch(tmp_path / "Form1.Designer.cs"))
    assert ignorer.skip_file(touch(tmp_path / "Api.g.cs"))
    assert ignorer.skip_file(touch(tmp_path / "obj" / "A.cs"))
    marked = touch(tmp_path / "Marked.cs", "// <copyright/>\n// <auto-generated>\nclass A { }\n")
    assert is_generated(marked)
    assert not is_generated(touch(tmp_path / "Plain.cs", "using System;\n// <auto-generated>\n"))


def test_hidden_and_build_folders_are_skipped(tmp_path: Path) -> None:
    ignorer = Ignorer()
    assert ignorer.skip_folder(tmp_path / ".git")
    assert ignorer.skip_folder(tmp_path / "bin")
    assert ignorer.skip_folder(tmp_path / "OBJ")
    assert not ignorer.skip_folder(tmp_path / "src")
